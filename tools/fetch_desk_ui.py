#!/usr/bin/env python3
"""Pin, verify and embed di.iiii's desk UI files (docs/DI_DESK_UI_PLAN.md, step V1).

desk_ui.lock names a di.iiii commit, the files and the sha256 of every raw file and of
its gzip -9 output. This script fetches the files at that commit (or reads a local
di.iiii checkout), checks them against the lock, gzips them deterministically and
writes include/desk_ui_gz.h.

  python3 tools/fetch_desk_ui.py                     fetch from GitHub, verify, write the header
  python3 tools/fetch_desk_ui.py --from ../di.iiii   read a local checkout (it must be at the locked commit's files)
  python3 tools/fetch_desk_ui.py --cache DIR         also write the verified raw files to DIR (tools/simulate_node.py reads them)
  python3 tools/fetch_desk_ui.py --check             regenerate in memory, fail if the committed header differs
  python3 tools/fetch_desk_ui.py --update [--commit <sha>] [--branch <name>]
                                                     rewrite the lock from what was fetched

stdlib only. The gzip stream has mtime 0 and no file name, so two runs give identical
bytes (same zlib; a different zlib build can differ: --check then names the gz hash).
"""
import argparse
import gzip
import hashlib
import io
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOCK = os.path.join(ROOT, "desk_ui.lock")
HEADER = os.path.join(ROOT, "include", "desk_ui_gz.h")
REPO = "dob-0/di.iiii"
UI_DIR = "serverXR/src/lighting/ui"
CONTRACT_VERSION = 1
MIME = {".html": "text/html", ".js": "application/javascript", ".css": "text/css"}


def sha256(b):
    return hashlib.sha256(b).hexdigest()


def gz9(b):
    buf = io.BytesIO()
    with gzip.GzipFile(filename="", mode="wb", fileobj=buf, compresslevel=9, mtime=0) as g:
        g.write(b)
    return buf.getvalue()


def fetch(name, commit, local):
    if local:
        with open(os.path.join(local, UI_DIR, name), "rb") as f:
            return f.read()
    url = "https://raw.githubusercontent.com/%s/%s/%s/%s" % (REPO, commit, UI_DIR, name)
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def ident(name):
    return "".join(c if c.isalnum() else "_" for c in name)


def render(lock, blobs):
    o = ["// GENERATED by tools/fetch_desk_ui.py from desk_ui.lock. Do not edit.",
         "// di.iiii %s (%s), contract %d" % (lock["commit"], lock["branch"], lock["contract_version"]),
         "#pragma once",
         "#include <stddef.h>",
         "#include <stdint.h>",
         "#ifndef PROGMEM",
         "#define PROGMEM",
         "#endif", "",
         'static const char DESK_UI_COMMIT[] = "%s";' % lock["commit"],
         "static constexpr int DESK_UI_CONTRACT_VERSION = %d;" % lock["contract_version"], ""]
    for f in lock["files"]:
        n, gz = ident(f["path"]), blobs[f["path"]]
        o.append('static const char desk_ui_etag_%s[] = "%s";' % (n, f["sha256"][:16]))
        o.append("static const size_t %s_gz_len = %d;" % (n, len(gz)))
        o.append("static const uint8_t %s_gz[] PROGMEM = {" % n)
        for i in range(0, len(gz), 16):
            o.append(",".join("0x%02x" % x for x in gz[i:i + 16]) + ",")
        o.append("};")
        o.append("")
    o += ["struct DeskUiFile {", "  const char* path;", "  const char* mime;",
          "  const uint8_t* data;", "  size_t len;", "  const char* etag;", "};",
          "static const DeskUiFile kDeskUiFiles[] = {"]
    for f in lock["files"]:
        n = ident(f["path"])
        o.append('  {"/%s", "%s", %s_gz, sizeof(%s_gz), desk_ui_etag_%s},'
                 % (f["path"], MIME[os.path.splitext(f["path"])[1]], n, n, n))
    o += ["};",
          "static constexpr size_t kDeskUiFileCount = sizeof(kDeskUiFiles) / sizeof(kDeskUiFiles[0]);", ""]
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--from", dest="local", help="local di.iiii checkout instead of GitHub")
    ap.add_argument("--cache", help="also write the raw files, verified against the lock, into this directory")
    ap.add_argument("--check", action="store_true", help="fail if the committed header differs from a fresh one")
    ap.add_argument("--update", action="store_true", help="rewrite desk_ui.lock from what was fetched")
    ap.add_argument("--commit", help="with --update: commit to pin (default: the lock's)")
    ap.add_argument("--branch", help="with --update: branch name to record")
    a = ap.parse_args()

    with open(LOCK) as f:
        lock = json.load(f)
    if a.update:
        if a.commit:
            lock["commit"] = a.commit
        if a.branch:
            lock["branch"] = a.branch
        lock["contract_version"] = CONTRACT_VERSION

    blobs, raws, bad = {}, {}, []
    for f in lock["files"]:
        raw = fetch(f["path"], lock["commit"], a.local)
        gz = gz9(raw)
        got = {"bytes": len(raw), "sha256": sha256(raw), "gz_bytes": len(gz), "gz_sha256": sha256(gz)}
        if a.update:
            f.update(got)
        else:
            for k in got:
                if f.get(k) != got[k]:
                    bad.append("%s: %s lock=%s got=%s" % (f["path"], k, f.get(k), got[k]))
        blobs[f["path"]] = gz
        raws[f["path"]] = raw
    if bad:
        sys.exit("lock mismatch (use --update to re-pin):\n  " + "\n  ".join(bad))
    if a.update:
        with open(LOCK, "w") as f:
            json.dump(lock, f, indent=2)
            f.write("\n")
        print("lock rewritten:", LOCK)

    if a.cache:
        os.makedirs(a.cache, exist_ok=True)
        for name, raw in raws.items():
            with open(os.path.join(a.cache, name), "wb") as f:
                f.write(raw)
        print("cached %d raw files in %s" % (len(raws), a.cache))

    text = render(lock, blobs)
    if a.check:
        try:
            with open(HEADER) as f:
                same = f.read() == text
        except OSError:
            same = False
        if not same:
            sys.exit("FAIL: %s differs from a fresh generation" % HEADER)
        print("PASS: header matches lock %s" % lock["commit"][:7])
        return
    with open(HEADER, "w") as f:
        f.write(text)
    print("wrote %s (%d bytes, %d files)" % (HEADER, len(text), len(lock["files"])))


if __name__ == "__main__":
    main()
